    def _image_reference(self) -> Image.Image | None:
        icon_file = (survivingmarsrelaunchedgame.unpacked_path / self.icon).with_suffix('.dds')
        img = Image.open(icon_file)
        left_img = img.crop((0, 0, img.size[0] / 2, img.size[1]))
        return left_img

    def get_image_reference(self) -> Image.Image | None:
        return self._image_reference

    def get_image_data_hash(self) -> str | None:
        return hashlib.sha256(self.get_image_reference().tobytes()).hexdigest()

    def get_wiki_filename(self) -> str:
        if not self.icon:
            return ''
        prefix = f'Building '
        icon_overrides = {
            'DomeOval': 'oval dome',
            'DomeMedium': 'medium dome',
        }
        if self.name in icon_overrides:
            icon_name = icon_overrides[self.name]
        else:
            icon_name = Path(self.icon.lower()).stem
        return f'{prefix}{icon_name}.png'

    def get_obsolete_wiki_filenames(self) -> list[str]:
        obsolete_names = []
        for basename in (self.display_name, Path(self.icon).stem):
            for prefix in ('Building ', 'Building-', 'Building - ', ''):
                obsolete_names.append(f'{prefix}{basename}.png')
        # obsolete_names.append(self.display_name + '.png')
        if 'Building - Mirror Sphere.png' in obsolete_names:
            obsolete_names.remove('Building - Mirror Sphere.png')

        return obsolete_names

    # def get_alternative_wiki_filenames(self) -> list[str]:
