class Unit(Building):

    def get_wiki_filename(self) -> str:
        if not self.icon or not self.display_name:
            return ''
        return WikiTextFormatter.normalize_page_title(f'{self.display_name}.png'.lower())

    def get_obsolete_wiki_filenames(self) -> list[str]:
        obsolete_names = super().get_obsolete_wiki_filenames() + [super().get_wiki_filename()]

        for other_name in ['Shuttle.png', 'Drone.png']:
            if other_name in obsolete_names:
                obsolete_names.remove(other_name)

        return obsolete_names
