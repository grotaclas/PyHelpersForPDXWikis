    def get_wiki_file_description(self) -> str:
        if self.display_name:
            fpk, _, file = self.icon.partition('/')
            file = Path(file).with_suffix('.dds')
            return  f'"Surviving Mars: Relaunched" icon for {self.get_class_name_as_wiki_page_title().lower()} [[{self.display_name}]]\n\nSource: <code>{file}</code> in <code>{fpk}.fpk</code>'
        else:
            return ''


