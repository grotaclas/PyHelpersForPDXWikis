class SMRAdvancedEntity(IconEntity):
    def __init__(self, name: str, display_name: str = '', **kwargs):
        display_name = display_name.replace('"', '')
        super().__init__(name, display_name, **kwargs)

    @cached_property
    def _image_reference(self) -> Image.Image | None:
        if self.icon:
            icon_file = (survivingmarsrelaunchedgame.unpacked_path / self.icon).with_suffix('.dds')
            if not icon_file.exists():
                for file in survivingmarsrelaunchedgame.unpacked_path.glob(f'DLC/*/{Path(self.icon).with_suffix(".dds")}'):
                    icon_file = file
            if icon_file.exists():
                return Image.open(icon_file)
            else:
                return None
        else:
            return None

    @cached_property
    def _image_reference_left_img(self) -> Image.Image | None:
        full_image = self._image_reference
        if full_image:
            left_img = full_image.crop((0, 0, full_image.size[0] / 2, full_image.size[1]))
            return left_img
        else:
            return None

    def get_image_reference(self) -> Image.Image | None:
        return self._image_reference

    def get_image_data_hash(self) -> str | None:
        reference = self.get_image_reference()
        if reference is None:
            return None
        return hashlib.sha256(reference.tobytes()).hexdigest()


