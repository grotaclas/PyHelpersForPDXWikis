class SMRAdvancedEntity(IconEntity):
    def __init__(self, name: str, display_name: str = '', **kwargs):
        display_name = display_name.replace('"', '')
        super().__init__(name, display_name, **kwargs)

    def get_image_reference(self) -> Path | None:
        if self.icon:
            return (survivingmarsrelaunchedgame.unpacked_path / self.icon).with_suffix('.dds')
        else:
            return None

    def get_image_data_hash(self) -> str | None:
        img = Image.open(self.get_image_reference())
        return hashlib.sha256(img.tobytes()).hexdigest()

